-- NightScene Framework - AMM Animation Pack Loader
-- ===================================================
-- Rig-aware pairing: only pairs animations that exist in BOTH
-- "Woman Average" AND "Man Average" rigs (standard street NPC skeletons).
-- Pairs by _a/_b suffix convention.

local AMMLoader = {}

AMMLoader.scanPaths = {
    "plugins/cyber_engine_tweaks/mods/AppearanceMenuMod/Collabs/Custom Poses/",
    "plugins/cyber_engine_tweaks/mods/NightScene/anims/",
}

-- Only packs matching one of these substrings (checked against entity_path,
-- category, and modder -- all case-insensitive) get registered. Everything else
-- in the manifest is skipped.
--
-- The manifest is generated by scanning AMM's Collabs/Custom Poses folder, which
-- sweeps up every pose pack installed for AMM. Most of those aren't built for
-- paired scenes and don't play correctly here -- some aren't even real pairs
-- (e.g. Leel Duck's "Enchanted Elegance" is 15 solo poses lettered pose_a
-- through pose_o, and the _a/_b pairing heuristic falsely reads the first two as
-- a two-actor animation). Restricted to PONC until the others are verified.
--
-- Matched on the PONC path specifically, NOT on the "PinkyDude" modder name --
-- PinkyDude also ships Mainline Carrying and Seductive Input vol 1/2, which are
-- separate packs.
--
-- Set to nil or {} to load the whole manifest again.
AMMLoader.packAllowlist = {
    "pleasures_of_nightcity",
}

--- Should this manifest pack be registered? Empty allowlist = allow everything.
local function isPackAllowed(pack)
    local allow = AMMLoader.packAllowlist
    if not allow or #allow == 0 then return true end

    local haystacks = {
        (pack.entity_path or ""):lower(),
        (pack.category or ""):lower(),
        (pack.modder or ""):lower(),
    }

    for _, pattern in ipairs(allow) do
        local needle = pattern:lower()
        for _, hay in ipairs(haystacks) do
            -- plain find (4th arg) so pattern magic chars can't misbehave
            if hay:find(needle, 1, true) then return true end
        end
    end
    return false
end

local function stripActorSuffix(name)
    if name:sub(-2) == "_a" then
        return name:sub(1, -3), "a"
    elseif name:sub(-2) == "_b" then
        return name:sub(1, -3), "b"
    end
    return name, nil
end

local function scanDirRecursive(basePath, results)
    results = results or {}
    local ok, entries = pcall(dir, basePath)
    if not ok or not entries then return results end
    for _, entry in ipairs(entries) do
        local name = entry.name or entry
        if type(name) == "string" then
            if name:match("%.lua$") then
                table.insert(results, basePath .. name)
            elseif not name:match("%.") then
                scanDirRecursive(basePath .. name .. "/", results)
            end
        end
    end
    return results
end

local function loadCollabFile(filePath)
    local ok, result = pcall(dofile, filePath)
    if ok and type(result) == "table" and result.anims and result.entity_path then
        return result
    end
    return nil
end

--- Rig-aware pairing: pairs from Woman Average + Man Average (MF)
--- and Woman Average _a/_b within itself (FF).
function AMMLoader.RegisterPack(pack)
    local packName = pack.category or pack.modder or "Unknown"
    local entityPath = pack.entity_path or ""
    local registered = 0

    -- Extract animation lists for standard rigs
    local femaleAnims = {} -- set: name -> true
    local maleAnims = {}   -- set: name -> true

    if pack.anims["Woman Average"] and type(pack.anims["Woman Average"]) == "table" then
        for _, name in ipairs(pack.anims["Woman Average"]) do
            femaleAnims[name] = true
        end
    end

    if pack.anims["Man Average"] and type(pack.anims["Man Average"]) == "table" then
        for _, name in ipairs(pack.anims["Man Average"]) do
            maleAnims[name] = true
        end
    end

    local femaleCount = 0
    for _ in pairs(femaleAnims) do femaleCount = femaleCount + 1 end
    local maleCount = 0
    for _ in pairs(maleAnims) do maleCount = maleCount + 1 end

    -- === MF Pairing: Woman Average + Man Average ===
    -- Convention: _a = male/active position, _b = female/passive position
    -- Only iterate _a names to avoid duplicate registrations
    if femaleCount > 0 and maleCount > 0 then
        local mfPaired = {}
        for animName, _ in pairs(femaleAnims) do
            local baseName, role = stripActorSuffix(animName)
            if role == "a" and not mfPaired[baseName] then
                local partnerB = baseName .. "_b"
                -- Both _a and _b must exist in BOTH rigs
                if femaleAnims[partnerB] and maleAnims[animName] and maleAnims[partnerB] then
                    mfPaired[baseName] = true
                    local id = packName:gsub("%s+", "_"):lower() .. "_mf_" .. baseName:gsub("%s+", "_"):lower()
                    local displayName = baseName:gsub("_", " ")
                    local tags = "amm,workspot,paired,mf," .. packName:gsub("%s+", "_"):lower()

                    -- Slot 0 = _a, slot 1 = _b -- matching the MBF and FF
                    -- branches below. This used to pass partnerB (_b) into slot
                    -- 0, so MF animations had the OPPOSITE slot convention to
                    -- every other branch. Packs with both Man Average and Woman
                    -- Average rigs register the same base animation twice (once
                    -- _mf_, once _ff_), and since scene selection now picks
                    -- randomly from all "paired" animations, the player's
                    -- Dom/Sub slot silently flipped meaning depending on which
                    -- variant got drawn.
                    local ok, result = pcall(
                        Game['NightSceneAPI::RegisterAMMAnimation;StringStringStringStringStringStringString'],
                        id, packName, displayName, entityPath, animName, partnerB, tags
                    )
                    if ok and result then registered = registered + 1 end
                end
            end
        end
    end

    -- === MBF Pairing: Woman Average + Big (Male Big) ===
    local bigAnims = {}
    if pack.anims["Big"] and type(pack.anims["Big"]) == "table" then
        for _, name in ipairs(pack.anims["Big"]) do
            bigAnims[name] = true
        end
    end

    local bigCount = 0
    for _ in pairs(bigAnims) do bigCount = bigCount + 1 end

    -- Convention: _a = female position in mbf packs, _b = Big male position
    -- (gh0st bedroom_mbf has _a in Woman Average, _b in Big)
    if femaleCount > 0 and bigCount > 0 then
        local mbfPaired = {}
        for animName, _ in pairs(femaleAnims) do
            local baseName, role = stripActorSuffix(animName)
            if role == "a" and not mbfPaired[baseName] then
                local partnerB = baseName .. "_b"
                if bigAnims[partnerB] then
                    mbfPaired[baseName] = true
                    local id = packName:gsub("%s+", "_"):lower() .. "_mbf_" .. baseName:gsub("%s+", "_"):lower()
                    local displayName = baseName:gsub("_", " ")
                    local tags = "amm,workspot,paired,mbf," .. packName:gsub("%s+", "_"):lower()

                    -- animFemale = _a (female), animMale = _b (Big male)
                    local ok, result = pcall(
                        Game['NightSceneAPI::RegisterAMMAnimation;StringStringStringStringStringStringString'],
                        id, packName, displayName, entityPath, animName, partnerB, tags
                    )
                    if ok and result then registered = registered + 1 end
                end
            end
        end
    end

    -- === FF Pairing: _a/_b pairs within Woman Average only ===
    -- Only if no Man Average rig (dedicated FF packs) or pack name hints FF
    if femaleCount > 0 then
        local ffPairs = {}
        for femaleName, _ in pairs(femaleAnims) do
            local baseName, role = stripActorSuffix(femaleName)
            if role == "a" then
                local partner = baseName .. "_b"
                if femaleAnims[partner] and not ffPairs[baseName] then
                    ffPairs[baseName] = { a = femaleName, b = partner }
                end
            end
        end

        for baseName, pair in pairs(ffPairs) do
            -- Register as FF: both actors are female
            -- animFemale = _a (subject/V), animMale = _b (partner NPC)
            -- We tag as "ff" so scene selection can filter by NPC gender
            local id = packName:gsub("%s+", "_"):lower() .. "_ff_" .. baseName:gsub("%s+", "_"):lower()
            local displayName = baseName:gsub("_", " ") .. " (FF)"
            local tags = "amm,workspot,paired,ff," .. packName:gsub("%s+", "_"):lower()

            local ok, result = pcall(
                Game['NightSceneAPI::RegisterAMMAnimation;StringStringStringStringStringStringString'],
                id, packName, displayName, entityPath, pair.a, pair.b, tags
            )
            if ok and result then registered = registered + 1 end
        end
    end

    return registered
end

AMMLoader.manifestPath = "anims/amm_manifest.lua"

function AMMLoader.LoadAll()
    print("[NightScene] AMM Loader: Loading from manifest...")

    local manifestPaths = {
        "anims/amm_manifest.lua",
        "plugins/cyber_engine_tweaks/mods/NightScene/anims/amm_manifest.lua",
    }

    local ok, packs = false, nil
    for _, path in ipairs(manifestPaths) do
        ok, packs = pcall(dofile, path)
        if ok and type(packs) == "table" then
            print("[NightScene] AMM Loader: Loaded manifest from: " .. path)
            break
        end
    end

    if not ok or type(packs) ~= "table" then
        ok, packs = pcall(require, "anims/amm_manifest")
    end
    if not ok or type(packs) ~= "table" then
        print("[NightScene] AMM Loader: Could not load manifest: " .. tostring(packs))
        packs = {}
    end

    local totalPacks = 0
    local totalAnims = 0
    local skippedPacks = 0

    for _, pack in ipairs(packs) do
        if isPackAllowed(pack) then
            local count = AMMLoader.RegisterPack(pack)
            if count > 0 then
                totalAnims = totalAnims + count
                totalPacks = totalPacks + 1
                print("[NightScene] AMM Loader: " .. (pack.category or pack.modder or "?") .. " -> " .. count .. " pairs")
            end
        else
            skippedPacks = skippedPacks + 1
        end
    end

    print("[NightScene] AMM Loader: Done. " .. totalPacks .. " packs, " .. totalAnims
        .. " paired animations (" .. skippedPacks .. " packs skipped by allowlist).")
    return totalPacks, totalAnims
end

return AMMLoader
